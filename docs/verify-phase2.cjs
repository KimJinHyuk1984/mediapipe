const { chromium } = require("playwright");
const assert = require("node:assert/strict");

(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const context = await browser.newContext();
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("response", r => { if (r.status() >= 400) errors.push(r.status() + " " + r.url()); });
  await page.goto("http://127.0.0.1:8000/mediapipe/level1/");
  assert.equal(await page.locator('[data-widget="landmark-map"][data-widget-ready="true"]').count(), 1);
  assert.equal(await page.locator('[data-widget="angle-slider"][data-widget-ready="true"]').count(), 1);
  assert.equal(await page.locator('[data-widget="state-machine"][data-widget-ready="true"]').count(), 1);
  assert.equal(await page.locator(".landmark-point").count(), 33);
  await page.locator('[data-widget="landmark-map"] input[type="checkbox"]').check();
  assert.ok(await page.locator('[data-widget="landmark-map"] .interactive-widget.today-only').count());
  await page.locator('.landmark-point[data-landmark="25"]').focus();
  await page.keyboard.press("Enter");
  assert.match(await page.locator('[data-widget="landmark-map"] .widget-readout').innerText(), /25.*LEFT_KNEE/);
  assert.match(await page.locator('[data-widget="landmark-map"] .widget-code').innerText(), /landmarks\[25\]/);
  const angle = page.locator('[data-widget="angle-slider"]');
  const input = angle.locator('input[type="range"]');
  for (let value = 40; value <= 180; value += 1) {
    await input.evaluate((el, v) => { el.value = v; el.dispatchEvent(new Event("input", { bubbles: true })); }, value);
    const diff = Number(await angle.getAttribute("data-dot-angle")) - Number(await angle.getAttribute("data-atan-angle"));
    assert.ok(Math.abs(diff) <= 0.0001, value + " diff=" + diff);
  }
  await input.focus();
  await page.keyboard.press("ArrowLeft");
  assert.equal(await input.inputValue(), "179");
  const state = page.locator('[data-widget="state-machine"]');
  await state.getByRole("button", { name: "초기화" }).click();
  await state.getByRole("button", { name: "스쿼트 1회 재생" }).click();
  await page.waitForFunction(() => document.querySelector('[data-widget="state-machine"] .interactive-widget')?.dataset.running === "false", null, { timeout: 10000 });
  const naive = Number(await state.locator('[data-counter="naive"]').innerText());
  const smart = Number(await state.locator('[data-counter="smart"]').innerText());
  assert.ok(naive > smart && smart === 1, `${naive}/${smart}`);
  await state.getByRole("button", { name: "정자세 없이 주저앉기" }).click();
  await page.waitForFunction(() => document.querySelector('[data-widget="state-machine"] .interactive-widget')?.dataset.running === "false", null, { timeout: 10000 });
  assert.equal(Number(await state.locator('[data-counter="smart"]').innerText()), 0);
  await page.keyboard.press("p");
  assert.equal(await page.locator("body").evaluate(el => el.classList.contains("is-presenting")), true);
  await page.locator('[data-widget="angle-slider"] input').focus();
  await page.keyboard.press("ArrowLeft");
  assert.equal(await page.locator(".presentation-counter").innerText(), "10 / 12");
  const before = await page.locator("[data-widget=angle-slider] input").inputValue();
  await page.keyboard.press("ArrowLeft");
  assert.notEqual(await page.locator("[data-widget=angle-slider] input").inputValue(), before);
  assert.equal(await page.locator(".presentation-counter").innerText(), "10 / 12");
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 375, height: 812 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.emulateMedia({ reducedMotion: "reduce" });
  await state.getByRole("button", { name: "초기화" }).click();
  await state.getByRole("button", { name: "스쿼트 1회 재생" }).click();
  assert.equal(await state.locator('[data-counter="smart"]').innerText(), "1");
  await browser.close();
  assert.deepEqual(errors, []);
  console.log("PASS widgets, angle parity 40-180, state playback, keyboard, presentation focus, 375px, reduced motion");
})().catch(e => { console.error(e); process.exit(1); });
